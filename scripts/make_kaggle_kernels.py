"""Generate Kaggle kernels from the notebook templates.

Training session (notebooks/kaggle_train.ipynb): several (exp, seed) runs as parallel
subprocesses. Resume with --resume-from <previous slug>; its output is attached as input and
every run must find its checkpoint (RESUME_REQUIRED) before `--resume auto`.

    python scripts/make_kaggle_kernels.py --slug pv-reach --runs reach_dr:0,reach_dr:1 \
        --device cpu --sha $(git rev-parse HEAD)

Evaluation session (notebooks/kaggle_eval.ipynb): ';;'-separated commands run in parallel on
the results/ trees of the kernels given by --inputs (e.g. trained checkpoints).

    python scripts/make_kaggle_kernels.py --slug pv-eval --inputs pv-push-tqc-r1 \
        --commands "python -m projectv.eval.heldout_sweep ...;; python -m ..." --sha <sha>

    kaggle kernels push -p kaggle/<slug> [--accelerator NvidiaTeslaT4]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "notebooks" / "kaggle_train.ipynb"
EVAL_TEMPLATE = ROOT / "notebooks" / "kaggle_eval.ipynb"
USER = "bipin14"


def train_params(args: argparse.Namespace) -> str:
    runs = [(r.split(":")[0], int(r.split(":")[1])) for r in args.runs.split(",")]
    lines = [
        "# PARAMETERS (generated by scripts/make_kaggle_kernels.py)",
        f"RUNS = {runs!r}",
        f"DEVICE = {args.device!r}",
        f"SHA = {args.sha!r}",
        f"MAX_HOURS = {args.max_hours!r}",
        f"ALGO = {args.algo!r}",
        f"EXTRA = {args.extra!r}",
        f"RESUME_REQUIRED = {bool(args.resume_from)!r}",
    ]
    return "\n".join(lines) + "\n"


def eval_params(args: argparse.Namespace) -> str:
    cmds = [c.strip() for c in args.commands.split(";;") if c.strip()]
    lines = [
        "# PARAMETERS (generated by scripts/make_kaggle_kernels.py --commands)",
        f"COMMANDS = {cmds!r}",
        f"SHA = {args.sha!r}",
    ]
    return "\n".join(lines) + "\n"


def write_kernel(slug: str, nb: dict, gpu: bool, sources: list[str]) -> Path:
    out = ROOT / "kaggle" / slug
    out.mkdir(parents=True, exist_ok=True)
    (out / "kaggle_train.ipynb").write_text(json.dumps(nb, indent=1), encoding="utf-8")
    meta = {
        "id": f"{USER}/{slug}",
        "title": slug,
        "code_file": "kaggle_train.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": gpu,
        "enable_internet": True,
        "dataset_sources": [],
        "kernel_sources": [f"{USER}/{s}" for s in sources],
        "competition_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return out


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--slug", required=True)
    p.add_argument("--runs", default="", help="exp:seed,exp:seed,... (training session)")
    p.add_argument("--commands", default="", help="';;'-separated commands (evaluation session)")
    p.add_argument("--inputs", default="", help="comma-separated kernel slugs attached as inputs")
    p.add_argument("--device", default="cpu", help="cpu | cuda-spread (round-robin over GPUs)")
    p.add_argument("--sha", required=True, help="git commit to check out")
    p.add_argument("--max-hours", type=float, default=11.0)
    p.add_argument("--algo", default="", help="algo config override (fallback ladder)")
    p.add_argument("--extra", default="", help="extra train.py args")
    p.add_argument("--resume-from", default="", help="previous kernel slug")
    p.add_argument("--gpu", action="store_true")
    args = p.parse_args()
    assert bool(args.runs) != bool(args.commands), "give exactly one of --runs / --commands"

    template, params = (
        (EVAL_TEMPLATE, eval_params(args)) if args.commands else (TEMPLATE, train_params(args))
    )
    nb = json.loads(template.read_text(encoding="utf-8"))
    cell = next(c for c in nb["cells"] if "".join(c["source"]).startswith("# PARAMETERS"))
    cell["source"] = params.splitlines(keepends=True)
    sources = [s for s in [args.resume_from, *args.inputs.split(",")] if s]
    print(f"wrote {write_kernel(args.slug, nb, args.gpu, sources)}")


if __name__ == "__main__":
    main()
